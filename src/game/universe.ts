/**
 * Returns clean initial progress state mapping each universe ID (0..40) to 0%
 */
export function getInitialUniverseProgress(): Record<number, number> {
  const map: Record<number, number> = {};
  for (let i = 0; i <= TOTAL_UNIVERSES_COUNT; i++) {
    map[i] = 0;
  }
  return map;
}

