export interface EnvironmentalHazard {
  id: string;
  name: string;
  icon: string;
  description: string;
  buffSummary: string;
}

export interface UniverseSector {
  id: number; // 0 (Black Hole) or 1 to 40
  name: string;
  code: string;
  clusterId: number;
  vietnameseTitle: string;
  description: string;
  dangerRating: number; // 1 to 10+
  recommendedStars: number; // 1 to 6
  recommendedCombatPower: number; // CP suggestion
  bossName: string;
  bossTitle: string;
  themeColor: string;
  accentColor: string;
  nodeX: number; // Spatial position percentage (5 to 95)
  nodeY: number; // Spatial position percentage (5 to 95)
  totalWaves: number; // Waves to reach 100% conquest
  rewardGold: number; // Gold reward on reaching 100% conquest
  firstClearGems: number; // First-time 100% conquest gems reward
  firstClearShards: { fighterId: string; count: number }; // First-time fighter shards
  hazard: EnvironmentalHazard;
  isBlackHole?: boolean;
}

